"""Domain data models for Local Evidence-backed Generation, Citations, and Abstention."""

import uuid
from datetime import datetime, timezone

from pydantic import BaseModel, Field


def utc_now() -> datetime:
    """Return timezone-aware current UTC datetime."""
    return datetime.now(timezone.utc)


class Citation(BaseModel):
    """
    Verifiable citation pointing to an exact immutable article version.
    Guarantees citation IDs exist and quotes match original publisher text.
    """

    citation_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    article_id: str
    version: int = 1
    source_id: str
    quote: str = Field(..., description="Exact verified quote from publisher body text")
    canonical_url: str = ""
    is_valid: bool = True


class StructuredClaim(BaseModel):
    """A factual claim generated by the model paired with its supporting citations."""

    claim_text: str
    citations: list[Citation] = Field(default_factory=list)
    has_support: bool = True


class GenerationInput(BaseModel):
    """Input payload for evidence-backed generation."""

    query: str = Field(..., min_length=3, max_length=2000, description="Analytical query")
    story_id: str | None = Field(default=None, description="Optional target story cluster")
    source_id: str | None = Field(default=None, description="Optional source filter")
    max_passages: int = Field(default=6, ge=1, le=10, description="Strict context budget")


class GenerationOutput(BaseModel):
    """Output envelope for local evidence-backed generation with abstention."""

    generation_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    query: str
    answer_markdown: str
    claims: list[StructuredClaim] = Field(default_factory=list)
    citations: list[Citation] = Field(default_factory=list)
    abstained: bool = False
    abstention_reason: str | None = None
    passages_used: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    latency_ms: int = 0
    model_name: str = "insightbot-local-v1"
    is_stale: bool = False
    generated_at: datetime = Field(default_factory=utc_now)


class StoryBriefingResponse(BaseModel):
    """Structured factual briefing for an event story cluster."""

    story_id: str
    story_title: str
    story_version: int
    briefing_markdown: str
    claims: list[StructuredClaim] = Field(default_factory=list)
    citations: list[Citation] = Field(default_factory=list)
    abstained: bool = False
    abstention_reason: str | None = None
    generated_at: datetime = Field(default_factory=utc_now)
    is_stale: bool = False
